import typescript from "@rollup/plugin-typescript";
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { patternSources, rawText } from "./scripts/rollup-plugins.mjs";

const pkgRoot = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const tsconfig = join(pkgRoot, "tsconfig.json");
const PATTERN_DIR = join(pkgRoot, "overlay", "patterns");
const LOOK_SLOT = "__AURORA_LOOK__";
const SCHEME_SLOT = "__AURORA_SCHEME__";

function overlayHtml() {
    return {
        name: "overlay-html",
        writeBundle() {
            const css = execFileSync(
                join(pkgRoot, "node_modules", ".bin", "tailwindcss"),
                ["-i", join(pkgRoot, "overlay", "overlay.css"), "--minify"],
                {
                    cwd: pkgRoot,
                    encoding: "utf8",
                    stdio: ["ignore", "pipe", "inherit"],
                }
            ).trim();
            const js = readFileSync(
                join(pkgRoot, "dist", "overlay.js"),
                "utf8"
            ).replaceAll("</script", "<\\/script");
            const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8" />
<meta name="color-scheme" content="${SCHEME_SLOT}" />
<style>${css}</style>
</head>
<body class="h-screen overflow-hidden">
<script id="aurora-look" type="application/json">${LOOK_SLOT}</script>
<script>${js}</script>
</body>
</html>`;
            // Committed because the publishing service builds src/index.ts with esbuild and runs no bundler plugins.
            const out = join(pkgRoot, "src", "overlay-html.ts");
            const source =
                `// Generated by rollup.config.mjs. Do not edit by hand.\n` +
                `export const OVERLAY_HTML = ${JSON.stringify(html)};\n`;
            // Skipping identical writes keeps the dev server's rebuild-on-change from looping.
            if (!existsSync(out) || readFileSync(out, "utf8") !== source)
                writeFileSync(out, source);
        },
    };
}

function webviewHtml() {
    return {
        name: "webview-html",
        writeBundle() {
            const shellPath = join(pkgRoot, "dist", "shell.cjs");
            delete require.cache[require.resolve(shellPath)];
            const { shellHtml } = require(shellPath);
            const js = readFileSync(
                join(pkgRoot, "dist", "webview.js"),
                "utf8"
            ).replaceAll("</script", "<\\/script");
            // Committed because the publishing service builds src/index.ts with esbuild and runs no bundler plugins.
            const out = join(pkgRoot, "src", "webview-html.ts");
            const source =
                `// Generated by rollup.config.mjs. Do not edit by hand.\n` +
                `export const WEBVIEW_HTML = ${JSON.stringify(shellHtml(js))};\n`;
            if (!existsSync(out) || readFileSync(out, "utf8") !== source)
                writeFileSync(out, source);
        },
    };
}

const webview = {
    input: "webview/main.ts",
    output: { file: "dist/webview.js", format: "iife" },
    plugins: [patternSources(PATTERN_DIR), rawText(), typescript({ tsconfig })],
};

const shell = {
    input: "src/webview-shell.ts",
    output: { file: "dist/shell.cjs", format: "cjs", exports: "named" },
    plugins: [typescript({ tsconfig }), webviewHtml()],
};

const overlay = {
    input: "overlay/main.ts",
    output: { file: "dist/overlay.js", format: "iife" },
    plugins: [
        patternSources(PATTERN_DIR),
        rawText(),
        typescript({ tsconfig }),
        overlayHtml(),
    ],
};

const driver = {
    input: "src/index.ts",
    output: { file: "dist/main.js", format: "cjs", exports: "named" },
    plugins: [typescript({ tsconfig })],
};

export default [overlay, webview, shell, driver];
