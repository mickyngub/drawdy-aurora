import typescript from "@rollup/plugin-typescript";
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const pkgRoot = dirname(fileURLToPath(import.meta.url));
const tsconfig = join(pkgRoot, "tsconfig.json");
const LOOK_SLOT = "__AURORA_LOOK__";
const SCHEME_SLOT = "__AURORA_SCHEME__";

function rawText() {
    return {
        name: "raw-text",
        resolveId(source, importer) {
            if (!source.endsWith("?raw") || !importer) return null;
            return resolve(dirname(importer), source);
        },
        load(id) {
            if (!id.endsWith("?raw")) return null;
            const file = id.slice(0, -"?raw".length);
            this.addWatchFile(file);
            return `export default ${JSON.stringify(readFileSync(file, "utf8"))};`;
        },
    };
}

function overlayHtml() {
    return {
        name: "overlay-html",
        writeBundle() {
            const css = execFileSync(
                join(pkgRoot, "node_modules", ".bin", "tailwindcss"),
                ["-i", join(pkgRoot, "overlay", "overlay.css"), "--minify"],
                {
                    cwd: pkgRoot,
                    encoding: "utf8",
                    stdio: ["ignore", "pipe", "inherit"],
                }
            ).trim();
            const js = readFileSync(
                join(pkgRoot, "dist", "overlay.js"),
                "utf8"
            ).replaceAll("</script", "<\\/script");
            const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8" />
<meta name="color-scheme" content="${SCHEME_SLOT}" />
<style>${css}</style>
</head>
<body class="h-screen overflow-hidden">
<script id="aurora-look" type="application/json">${LOOK_SLOT}</script>
<script>${js}</script>
</body>
</html>`;
            // Committed because the publishing service builds src/index.ts with esbuild and runs no bundler plugins.
            const out = join(pkgRoot, "src", "overlay-html.ts");
            const source =
                `// Generated by rollup.config.mjs. Do not edit by hand.\n` +
                `export const OVERLAY_HTML = ${JSON.stringify(html)};\n`;
            // Skipping identical writes keeps the dev server's rebuild-on-change from looping.
            if (!existsSync(out) || readFileSync(out, "utf8") !== source)
                writeFileSync(out, source);
        },
    };
}

const overlay = {
    input: "overlay/main.ts",
    output: { file: "dist/overlay.js", format: "iife" },
    plugins: [rawText(), typescript({ tsconfig }), overlayHtml()],
};

const driver = {
    input: "src/index.ts",
    output: { file: "dist/main.js", format: "cjs", exports: "named" },
    plugins: [typescript({ tsconfig })],
};

export default [overlay, driver];
